"""One-column layout of the compute-matched table (Table tab:compute in main.tex).

Reads outputs/crs/analysis/n932_e3_compute.json (written by scripts/n932_e3_compute.py) and writes
paper/tex/tables/tab_compute_col.tex: rows = comparison, columns = Qwen3.5 size; each cell = test Delta R@20 per row
(ReMaRk - Rank-GRPO, paired bootstrap 95% CI) over GPU-hours ReMaRk / Rank-GRPO. Same cell format as n932_e3_compute.fmt_cell.
Usage: python3 remark/scripts/make_tab_compute_col.py   (rerun after n932_e3_compute.py)
"""

from __future__ import annotations

import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
SRC = ROOT / "outputs/crs/analysis/n932_e3_compute.json"
OUT = ROOT / "paper/tex/tables/tab_compute_col.tex"
ROWS = [("1k_2k", "1k vs.\\ 2k steps"), ("2k_4k", "2k vs.\\ 4k steps"), ("best", "best vs.\\ best")]


def cell(c: dict | None) -> str:
    if c is None:  # comparison not run at this size
        return "--"
    if c.get("diff") is None:
        return "pending"
    r = c["diff"]["row"]
    lo, hi = (100 * x for x in r["ci"])
    v = 100 * r["diff"]
    sgn = lambda x: f"{x:+.2f}".replace("-", "$-$")  # noqa: E731
    num = lambda x: f"{x:.2f}".replace("-", "$-$")  # noqa: E731
    mac = "\\up" if lo > 0 else ("\\dn" if hi < 0 else "\\ns")
    ga, gb = c.get("gpuh_remark"), c.get("gpuh_rankgrpo")
    g = f"{ga['gpu_hours']:.0f} / {gb['gpu_hours']:.0f} GPU-h" if ga and gb else "--"
    sm = "{\\scriptsize\\color{cigray}%s}"  # three-line cell: Delta, CI, GPU-h (\\dstack holds two lines only)
    return (f"\\begin{{tabular}}[t]{{@{{}}c@{{}}}}{mac}{{{sgn(v)}}}\\\\[-1.5pt]" + sm % f"[{num(lo)},{num(hi)}]"
            + "\\\\[-1.5pt]" + sm % g + "\\end{tabular}")


def main() -> None:
    res = json.loads(SRC.read_text())
    lines = ["% generated by remark/scripts/make_tab_compute_col.py from outputs/crs/analysis/n932_e3_compute.json;"
             " do not edit by hand", "\\begin{tabular}{@{}l ccc@{}}", "\\toprule",
             " & 2B & 4B & 9B \\\\", "\\midrule"]
    for key, name in ROWS:
        lines.append(name + " & " + " & ".join(cell(res["cells"].get(s, {}).get(key) if key in res["cells"].get(s, {}) else None) for s in ("2B", "4B", "9B"))
                     + " \\\\")
    lines += ["\\bottomrule", "\\end{tabular}"]
    OUT.write_text("\n".join(lines) + "\n")
    print(OUT)


if __name__ == "__main__":
    main()
