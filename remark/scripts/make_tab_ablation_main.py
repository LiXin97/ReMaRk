"""Write the compact main-text ablation table (Table 4, tab:ablation): one column, arms grouped by advantage scale.

Author script (2026-10-02). Reads outputs/crs/analysis/paper_test_tables.json (crs_val_table.py with
configs/paper_test_tables.json; arms and paired bootstrap differences over requests, 2,000 resamples, seed 42) and
writes paper/tex/tables/tab_ablation_main.tex. Row numbers are those used throughout the paper (make_ablation_tables.py);
the full table with the n=1 / n>=5 columns stays in the appendix (tab_ablation_test.tex). Missing differences print as
"--" and are listed on stdout.
"""
from __future__ import annotations

import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
SRC = ROOT / "outputs/crs/analysis/paper_test_tables.json"
OUT = ROOT / "paper/tex/tables/tab_ablation_main.tex"

# row -> (arm key, reward, sampling); scale is the block
SFT = (0, "sft")
GROUP = [(1, "single_group", "per-responder", "row"), (8, "singlethr_group", "per-responder", "request"),
         (9, "mean_group", "mean", "request"), (7, "union_group", "bounded sum", "request")]
BATCH = [(2, "single_batch", "per-responder", "row"), (3, "singlethr", "per-responder", "request"),
         (4, "consensusrw", "mean", "row"), (5, "consensus", "mean", "request"),
         (6, "union", "bounded sum", "request")]
BASE = "single_group"
TINT = {1: r"\baserow ", 7: r"\oursrow "}

# Row 9 (, 2B seed 3407, mean reward with per-group scaling) comes from its own readout files (10-06)
A9 = {"arm": "test_2B_consensus_group_s3407_p0c_step2000", "row": ROOT / "outputs/crs/analysis/n933_a_pair_row.json",
      "unit": ROOT / "outputs/crs/analysis/n933_a_pair_unit.json",
      "vs_base": ROOT / "outputs/crs/analysis/n933_a_vs_rankgrpo_row.json"}

missing: list[str] = []


def add_row9(arms: dict, pairs: list[dict]) -> None:
    def value(path: Path) -> float:
        for p in json.loads(path.read_text())["pairs"]:
            if Path(p["a"]).name == A9["arm"]:
                return p["R@20"]["a"]
        raise KeyError(A9["arm"])

    arms["mean_group"] = {"R@20": value(A9["row"]), "req_R@20": value(A9["unit"])}
    d = json.loads(A9["vs_base"].read_text())["pairs"][0]["R@20"]
    pairs.append({"a": "mean_group", "b": BASE, "all": {"row": [d["diff"], d["ci_low"], d["ci_high"]]}})


def find(pairs: list[dict], a: str, b: str) -> list[float] | None:
    """Per-row difference a - b over all requests, negating a stored b - a."""
    for p in pairs:
        if p["a"] == a and p["b"] == b:
            return p["all"]["row"]
        if p["a"] == b and p["b"] == a:
            v = p["all"]["row"]
            return [-v[0], -v[2], -v[1]]
    return None


def num(x: float) -> str:
    return f"{100 * x:.2f}"


def signed(x: float) -> str:
    if f"{abs(x):.2f}" == "0.00":  # rounds to zero: unsigned (10-09)
        return "0.00"
    return f"+{x:.2f}" if x >= 0 else f"$-${-x:.2f}"


def delta(d: list[float] | None) -> str:
    if d is None:
        return "--"
    v, lo, hi = (100 * t for t in d)
    tag = r"\up" if lo > 0 else (r"\dn" if hi < 0 else r"\ns")
    b = lambda x: "0.00" if f"{abs(x):.2f}" == "0.00" else (f"{x:.2f}" if x >= 0 else f"$-${-x:.2f}")
    return rf"{tag}{{{signed(v)}}} {{\scriptsize\color{{cigray}}[{b(lo)},{b(hi)}]}}"  # CI: no space (10-09)


def main() -> None:
    t = json.loads(SRC.read_text())["datasets"]["reddit_test"]
    arms, pairs = t["arms"], t["pairs"]
    add_row9(arms, pairs)
    trained = [k for _, k, *_ in GROUP + BATCH]

    def marks(col: str) -> dict[str, str]:
        # ties at the printed precision share a mark
        vals = sorted({num(arms[k][col]) for k in trained}, key=float, reverse=True)
        tag = {vals[0]: "best", vals[1]: "second"}
        return {k: tag[num(arms[k][col])] for k in trained if num(arms[k][col]) in tag}

    mk = {c: marks(c) for c in ("R@20", "req_R@20")}

    def cell(k: str, c: str) -> str:
        s = num(arms[k][c])
        m = mk[c].get(k)
        return rf"\{m}{{{s}}}" if m else s

    lines = [
        "% generated by remark/scripts/make_tab_ablation_main.py from outputs/crs/analysis/paper_test_tables.json;"
        " do not edit by hand",
        r"\renewcommand{\arraystretch}{1.08}",
        r"\begin{tabular}{@{}r ll r l r@{}}",
        r"\toprule",
        r" & reward & sampling & R@20 & $\Delta$ to row 1 & req. \\",
        r"\midrule",
        rf"0 & \multicolumn{{2}}{{@{{}}l}}{{SFT (no RL)}} & {num(arms['sft']['R@20'])} & & {num(arms['sft']['req_R@20'])} \\",
    ]
    for title, block in (("group scaling", GROUP), ("batch scaling", BATCH)):
        lines.append(rf"\multicolumn{{6}}{{@{{}}l}}{{\grp{{{title}}}}} \\")
        for r, k, reward, samp in block:
            if k == BASE:
                d = ""
            else:
                v = find(pairs, k, BASE)
                if v is None:
                    missing.append(f"{r}-1")
                d = delta(v)
            lines.append(f"{TINT.get(r, '')}{r} & {reward} & {samp} & {cell(k, 'R@20')} & {d} & {cell(k, 'req_R@20')}"
                         r" \\")
    lines += [r"\bottomrule", r"\end{tabular}", ""]
    OUT.write_text("\n".join(lines))
    print(f"wrote {OUT}")
    print("missing:", ", ".join(missing) if missing else "none")


if __name__ == "__main__":
    main()
